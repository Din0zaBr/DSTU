"""
Шифр на основе сети Фейстеля (ГОСТ-подобный).
Блок 64 бита, ключ 256 бит, 32 раунда, 8 S-блоков.
"""

import struct
import random
import os

KEY_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "key.txt")
MOD32 = 2 ** 32
BLOCK_SIZE = 8
ROUNDS = 32

# -----------------------------------------------------------------------------
# ЛОГИКА АЛГОРИТМА (краткая шпаргалка)
# -----------------------------------------------------------------------------
# 1. Блок открытого текста = 64 бита = 8 байт.
#    Делится на две половины по 32 бита: L (левая, в коде N1) и R (правая, N2).
#    Порядок байт: little-endian (<II = два uint32).
#
# 2. Ключ = 256 бит = 32 байта = 8 подключей по 32 бита: K[0]..K[7].
#
# 3. Порядок подключей по раундам (важно не путать):
#    Раунды 1–24:  K[0], K[1], K[2], K[3], K[4], K[5], K[6], K[7], затем снова K[0]...
#    Раунды 25–32: K[7], K[6], K[5], K[4], K[3], K[2], K[1], K[0].
#    (индекс: i < 24 → i % 8; иначе (31 - i) % 8)
#
# 4. Один раунд шифрования (вход: L, R; подключ Ki):
#    Шаг А: S_sum = (L + Ki) mod 2^32
#    Шаг Б: S_sum разбить на 8 тетрад (по 4 бита). Каждая тетрада — индекс в своей
#           строке S_BOX[i]. Результаты (по 4 бита) склеить → 32 бита (S_block_out).
#    Шаг В: S = циклический сдвиг S_block_out влево на 11 бит.
#    Шаг Г: L_new = R XOR S,   R_new = L  (половинки меняются местами, левая = старая правая XOR S).
#
# 5. После 32 раундов блок выдаётся как (R_final, L_final) — половинки в конце меняются местами.
#
# 6. Расшифрование: те же 32 раунда, но подключами в обратном порядке (с 32-го по 1-й).
# -----------------------------------------------------------------------------
# ПРИМЕР ОДНОГО РАУНДА (чтобы не путаться в шагах)
# -----------------------------------------------------------------------------
# Пусть в начале раунда: L = 0x00000001, R = 0x00000002, ключ раунда Ki = 0x00000003.
#
#   Шаг А — сложение с ключом:
#     S_sum = (L + Ki) mod 2^32 = 1 + 3 = 4.
#
#   Шаг Б — S-блок:
#     Число 4 в двоичном виде (32 бита): ...0000 0100.
#     Разбиваем на 8 тетрад (справа налево): [0,0,0,0,0,0,0,4].
#     S_BOX[0][0]=4, S_BOX[1][0]=14, ..., S_BOX[7][4]=0 (последняя тетрада = 4, строка 7).
#     Результат — 8 тетрад склеиваются в новое 32-битное число S_block_out.
#
#   Шаг В — сдвиг влево на 11:
#     S = rotate_left_11(S_block_out). Биты уезжают влево, вышедшие слева появляются справа.
#
#   Шаг Г — XOR и перестановка:
#     L_new = R XOR S = 0x00000002 XOR S,
#     R_new = L = 0x00000001.
#
# На следующий раунд идут уже (L_new, R_new).
# -----------------------------------------------------------------------------

S_BOX = [
    [4, 10, 9, 2, 13, 8, 0, 14, 6, 11, 1, 12, 7, 15, 5, 3],
    [14, 11, 4, 12, 6, 13, 15, 10, 2, 3, 8, 1, 0, 7, 5, 9],
    [5, 8, 1, 13, 10, 3, 4, 2, 14, 15, 12, 7, 6, 0, 9, 11],
    [7, 13, 10, 1, 0, 8, 9, 15, 14, 4, 6, 12, 11, 2, 5, 3],
    [6, 12, 7, 1, 5, 15, 13, 8, 4, 10, 9, 14, 0, 3, 11, 2],
    [4, 11, 10, 0, 7, 2, 1, 13, 3, 6, 8, 5, 9, 14, 15, 12],
    [13, 11, 4, 10, 7, 2, 1, 5, 0, 8, 15, 14, 9, 3, 12, 6],
    [1, 7, 14, 13, 0, 5, 8, 3, 4, 15, 10, 6, 9, 12, 11, 2],
]


def _get_subkey_index(i):
    """Номер подключа для раунда i (0..31): раунды 0–23 → K[0]..K[7] по кругу, 24–31 → в обратном порядке."""
    return i % 8 if i < 24 else (31 - i) % 8


def _rotate_left11(value):
    """Циклический сдвиг 32-битного числа влево на 11 бит."""
    return ((value << 11) | (value >> 21)) % MOD32


def s_block(value):
    """
    S-блок: 32 бита → 8 тетрад (по 4 бита). Каждая тетрада — индекс в S_BOX[i].
    Результат — 8 значений по 4 бита, склеенные в одно 32-битное число.
    """
    result = []
    binary_value = f"{value:032b}"  # 32 бита с ведущими нулями
    for i in range(8):
        search_id = int(binary_value[i * 4 : (i + 1) * 4], 2)  # i-я тетрада (0..15)
        result.append(f"{S_BOX[i][search_id]:04b}")
    return int("".join(result), 2)


def _feistel_round(N1, N2, Ki, show_steps, round_num):
    """
    Один раунд Фейстеля. Вход: N1 = L, N2 = R, Ki — подключ.
    А: L + Ki (mod 2^32) → Б: S-блок → В: сдвиг влево 11 → Г: L_new = R XOR S, R_new = L.
    """
    S_sum = (N1 + Ki) % MOD32           # Шаг А: сложение с ключом
    S_block_out = s_block(S_sum)        # Шаг Б: S-блок
    S = _rotate_left11(S_block_out)     # Шаг В: сдвиг влево на 11
    N1_new, N2_new = N2 ^ S, N1         # Шаг Г: XOR и обмен половинок

    if show_steps:
        print(f"Раунд {round_num}. До ключа: L = {N1:08X} ({N1:032b}), R = {N2:08X} ({N2:032b})")
        print(f"Ключ = {Ki:08X} ({Ki:032b})")
        print(f"Сложение с ключом = {S_sum:08X} ({S_sum:032b})")
        print(f"После S-блока = {S_block_out:08X} ({S_block_out:032b})")
        print(f"После сдвига на 11 = {S:08X} ({S:032b})")
        print(f"После XOR: L = {N1_new:08X} ({N1_new:032b}), R = {N2_new:08X} ({N2_new:032b})")

    return N1_new, N2_new


def encrypt(block, key, show_steps=True):
    """Шифрование: 32 раунда с подключами K[0]..K[7], K[0]..K[7], K[0]..K[7], K[7]..K[0]. В конце — обмен L↔R."""
    block = block.ljust(BLOCK_SIZE, b'\x00')
    N1, N2 = struct.unpack('<II', block)  # N1 = левая половина (L), N2 = правая (R)
    for i in range(ROUNDS):
        print("=" * 40)
        Ki = key[_get_subkey_index(i)]
        N1, N2 = _feistel_round(N1, N2, Ki, show_steps, i + 1)
    return struct.pack('<II', N2, N1)  # итог: сначала R, потом L (финальная перестановка)


def decrypt(block, key, show_steps=True):
    """Расшифрование: те же 32 раунда, но подключами в обратном порядке (раунд 32→1)."""
    block = block.ljust(BLOCK_SIZE, b'\x00')
    N1, N2 = struct.unpack('<II', block)
    for i in reversed(range(ROUNDS)):
        print("=" * 40)
        Ki = key[_get_subkey_index(i)]
        N1, N2 = _feistel_round(N1, N2, Ki, show_steps, ROUNDS - i)
    return struct.pack('<II', N2, N1)


def pad_message(message):
    encoded = message.encode('utf-8')
    size = ((len(encoded) + BLOCK_SIZE - 1) // BLOCK_SIZE) * BLOCK_SIZE
    # Вычисляет ближайшую длину блока, кратную BLOCK_SIZE и не меньшую чем BLOCK_SIZE
    return encoded.ljust(size, b'\x00')


def generate_key():
    key = [random.randint(0, 0xFFFFFFFF) for _ in range(8)]
    key_hex = ''.join(f"{k:08X}" for k in key)
    with open(KEY_FILE, "w") as f:
        f.write(key_hex)
    print(f"Ключ сгенерирован и сохранен в файл: {key_hex}")
    return key


def load_key():
    if not os.path.exists(KEY_FILE):
        print("Файл с ключом не найден! Сначала сгенерируйте ключ.")
        return None
    with open(KEY_FILE, "r") as f:
        return process_key(f.read().strip())


def process_key(key_str):
    try:
        key_bytes = bytes.fromhex(key_str)
        if len(key_bytes) != 32:
            raise ValueError
        key = [struct.unpack("<I", key_bytes[i:i + 4])[0] for i in range(0, 32, 4)]
        # Строка берёт 32 байта (key_bytes) и преобразует их в список из 8 целых чисел (каждое по 4 байта = 32 бита)
        # [0] потому что кортеж вернёт (число, )
        return key
    except ValueError:
        print("Ошибка: ключ должен быть 32-байтовым (64 HEX-символа)!")
        return None


def _format_binary(data):
    return ' '.join(f"{b:08b}" for b in data)


def _process_blocks(data, key, cipher_func):
    return b''.join(
        cipher_func(data[i:i + BLOCK_SIZE], key)
        for i in range(0, len(data), BLOCK_SIZE)
    )


